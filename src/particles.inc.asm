;================================================================
; particle_burst_hit: directional blood spray + impact flash
;----------------------------------------------------------------
; in: edi = x_px, esi = y_px, edx = face (of attacker)
;================================================================
particle_burst_hit:
	push rbx
	push r12
	push r13
	push r14
	push r15
	push rbp

	mov r12d, edi
	mov r13d, esi
	mov r14d, edx ; face

	; --- impact flash: 4 white sparks, very short ---
	mov ebp, 4
.flash:
	mov edi, 6
	call rng_smallrange
	mov ebx, eax

	mov edi, 6
	call rng_smallrange

	mov edx, ebx
	shl edx, 14
	mov ecx, eax
	shl ecx, 14

	mov edi, r12d
	shl edi, 16
	mov esi, r13d
	shl esi, 16

	mov r8d, 0xFFFFFFFF		; white
	mov r9d, 0x40FFC080		; warm fade

	push qword P_FLAG_WORLD_SPACE
	push qword 6
	call particle_spawn
	add rsp, 16

	dec ebp
	jnz .flash

	; --- blood: 8 droplets biased along facing direction ---
	mov ebp, 8
.blood:
	mov edi, 3
	call rng_smallrange		; -3..3
	mov ebx, eax			; perp

	mov edi, 2
	call rng_smallrange		; -2..2
	add eax, 3				; outward 1..5
	mov r15d, eax			; temp (stored in prologue)

	; same dispatch as chop, but along facing (not opposite)
	xor edi, edi
	xor esi, esi
	cmp r14d, 0				; FACE_DOWN
	jne .bh_down
	mov esi, r15d
	shl esi, 14
	mov edi, ebx
	shl edi, 14
	sub esi, 0x7000			; gentle upward arc
	jmp .bh_have
.bh_down:
	cmp r14d, 1				; FACE_UP
	jne .bh_up
	mov esi, r15d
	neg esi
	shl esi, 14
	mov edi, ebx
	shl edi, 14
	sub esi, 0x7000
	jmp .bh_have
.bh_up:
	cmp r14d, 2				; FACE_LEFT
	jne .bh_left
	mov edi, r15d
	neg edi
	shl edi, 14
	mov esi, ebx
	shl esi, 14
	sub esi, 0x7000
	jmp .bh_have
.bh_left:
	mov edi, r15d			; FACE_RIGHT
	shl edi, 14
	mov esi, ebx
	shl esi, 14
	sub esi, 0x7000
.bh_have:
	mov edx, edi
	mov ecx, esi

	mov edi, r12d
	shl edi, 16
	mov esi, r13d
	shl esi, 16

	mov r8d, 0xFFC00000		; bright blood
	mov r9d, 0xFF800000		; dark fade

	push qword (P_FLAG_GRAVITY | P_FLAG_WORLD_SPACE | P_FLAG_RECT)
	push qword 22
	call particle_spawn
	add rsp, 16

	dec ebp
	jnz .blood

	pop rbp
	pop r15
	pop r14
	pop r13
	pop r12
	pop rbx
	ret

;================================================================
; particle_burst_splash: water droplets in a radial ring + a
; bright central flash dot
;----------------------------------------------------------------
; in: edi = x_px, esi = y_px
;----------------------------------------------------------------
; uses burst_ring as the primitive.  droplets get gravity so they
; arc back down.  a brief white pixel marks the impact
;================================================================
particle_burst_splash:
	push rbx
	push r12
	push r13
	push rbp
	sub rsp, 8
	mov r12d, edi
	mov r13d, esi

	; --- 3 white foam sparks ---
	mov ebp, 3
.flash:
	mov edi, 2
	call rng_smallrange		; -2..2
	mov ebx, eax

	mov edi, 1
	call rng_smallrange
	sub eax, 2				; -3..-1, biased up

	mov edx, ebx
	shl edx, 13
	mov ecx, eax
	shl ecx, 13

	mov edi, r12d
	shl edi, 16
	mov esi, r13d
	shl esi, 16

	mov r8d, 0xFFFFFFFF		; pure white
	mov r9d, 0xFFC0E8FF		; fade to pale blue

	push qword (P_FLAG_RECT | P_FLAG_WORLD_SPACE | P_FLAG_GRAVITY)
	push qword 10
	call particle_spawn
	add rsp, 16

	dec ebp
	jnz .flash

	; --- ring of 6 1px droplets ---
	mov edi, r12d
	mov esi, r13d
	mov edx, 6				; count
	mov ecx, 0x08000		; speed_q
	mov r8d, 0xFFFFFFFF		; white
	mov r9d, 0xFFA8D8FF		;  blue
	push qword (P_FLAG_GRAVITY | P_FLAG_WORLD_SPACE)
	push qword 10			; life
	call particle_burst_ring
	add rsp, 16

	add rsp, 8
	pop rbp
	pop r13
	pop r12
	pop rbx
	ret

